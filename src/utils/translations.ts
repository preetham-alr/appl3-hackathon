export function t(key: string, lang: LanguageCode = 'en', fallback?: string): string {
  if (translations[key] && translations[key][lang]) {
    return translations[key][lang];
  }
  if (translations[key] && translations[key]['en']) {
    return translations[key]['en'];
  }
  return fallback || key;
}

/**
 * Dynamic Content Localization Helper
 */
export function getLocalizedText(text: string, lang: LanguageCode = 'en'): string {
  if (!text || lang === 'en') return text;
  const lower = text.toLowerCase();
  
  if (lower.includes('pothole') || lower.includes('road repair')) {
    return t('potholeReport', lang, text);
  }
  if (lower.includes('water') || lower.includes('pipe') || lower.includes('leakage')) {
    return t('waterOverflowReport', lang, text);
  }
  if (lower.includes('kisan')) {
    return t('pmKisanScheme', lang, text);
  }
  if (lower.includes('madhapur')) {
    return t('madhapurWard', lang, text);
  }
  if (lower.includes('hitec city') || lower.includes('hyderabad')) {
    return t('hitecCity', lang, text);
  }

  return text;
}
